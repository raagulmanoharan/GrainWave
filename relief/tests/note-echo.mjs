import assert from 'node:assert/strict';
import {NoteEcho} from '../note-echo.js';
import {LoopRack} from '../note-buffer.js';
const echo=new NoteEcho(),tone={type:'tone',role:'lead',freq:440,time:10,level:.2,pan:.3,monophonic:true};
echo.add(tone,.5);
assert.deepEqual(echo.due(10),[]);
const repeats=[...echo.due(10.45),...echo.due(10.95),...echo.due(11.45)];
assert.equal(repeats.length,3);
assert.deepEqual(repeats.map(n=>n.time),[10.5,11,11.5]);
assert(repeats.every(n=>n.freq===440&&n.pan===.3&&!n.monophonic));
assert(repeats[0].level<tone.level&&repeats[1].level<repeats[0].level&&repeats[2].level<repeats[1].level);
assert.deepEqual(echo.due(20),[]);
echo.add(tone,.5);echo.add({...tone,role:'loop:1'},.5);echo.cancel('lead');
assert(echo.due(10.5).every(n=>n.role==='echo:loop:1'));
assert.deepEqual(echo.due(20),[],'No burst of stale echoes after a stalled tab');
for(let i=0;i<1000;i++)echo.add(tone,.5);assert(echo.pending.length<=192);echo.clear();assert.equal(echo.pending.length,0);
const rack=new LoopRack();
rack.record({midi:60,time:0,point:{x:.2,y:.5}});
const first=rack.capture(500,true);
rack.record({midi:64,time:600,point:{x:.3,y:.5}});
const second=rack.capture(1000,false);
assert(first.echo);assert.equal(second.echo,false);
assert(rack.due(1000).some(n=>n.loopId===first.id&&n.echo));
first.echo=false;second.echo=true;
const next=rack.due(1500);assert(next.some(n=>n.loopId===first.id&&!n.echo));assert(next.some(n=>n.loopId===second.id&&n.echo));
rack.togglePause(1500);assert(rack.due(2000).every(n=>n.loopId!==second.id));
console.log('Echo repeats, decay, cancellation, bounded backlog and independent loop settings passed');
