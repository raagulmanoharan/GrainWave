import assert from 'node:assert/strict';
import {MotionExpression} from '../expression.js';
const e=new MotionExpression();
const p=(time,dx=.005)=>({id:'motion-1',confirmed:true,x:.5,y:.5,dx,dy:0,time,interval:83});
e.observe([p(83,.00001)],83);assert.equal(e.advance(83).note,false,'Residual jitter is silent');
e.observe([p(166)],166);assert.equal(e.advance(166).note,true,'Confirmed OpenCV travel triggers');
e.observe([p(166)],170);assert.equal(e.advance(170).note,false,'Same frame cannot retrigger');
e.observe([p(249)],249,{uncertain:true});assert.equal(e.advance(249).note,false,'Uncertain camera stops notes');
e.observe([{...p(332),confirmed:false}],332);assert.equal(e.advance(332).note,false,'Unconfirmed points ignored');
e.observe([p(415)],800);assert.equal(e.advance(800).note,false,'Old worker result ignored');
e.observe([p(900)],900);assert.equal(e.advance(900).note,true);
assert.equal(e.advance(1200).note,false,'Stationary scene releases notes');e.reset();assert.equal(e.active.size,0);
console.log('OpenCV expression, timing, camera uncertainty and release passed');

const {MotionArpeggio,MIN_NOTE_GAP,motionNoteGap}=await import('../motion-arpeggio.js');
assert(motionNoteGap(.15)>motionNoteGap(.5)&&motionNoteGap(.5)>motionNoteGap(1),'Movement continuously controls note density');
assert(motionNoteGap(1)>=MIN_NOTE_GAP&&motionNoteGap(.15)<450);
const gesture={time:0,midi:60,point:{x:.5,y:.5},level:1,sources:6};
const run=new MotionArpeggio(),notes=run.plan(gesture);
assert.equal(notes.length,2,'Keep energetic runs short');
assert(notes[0].at<200&&notes[1].at-notes[0].at>=MIN_NOTE_GAP,'Fast motion allows quick, distinct notes');
assert.notEqual(notes[0].at,notes[1].at-notes[0].at,'Runs have a gentle rhythmic push');
assert(!run.busy(notes.at(-1).at+MIN_NOTE_GAP),'No forced long pause after a run');
assert.deepEqual(run.plan({...gesture,time:500}),[],'Do not pile up bursts');
assert(run.plan({...gesture,time:1500}).length>0);
const softer=new MotionArpeggio().plan({...gesture,level:.82});
assert(softer[0].at>notes[0].at,'Softer gestures unfold more slowly');
console.log('Motion-responsive spacing, short runs and double-hit guard passed');
